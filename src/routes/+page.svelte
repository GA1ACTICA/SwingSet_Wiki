  <h1>Welcome to the SwingSet Engine wiki!</h1>

  <p>
    Looking to get started with 2D game development in Java? Meet <strong
      >SwingSet Engine</strong
    > – a small and lightweight game engine built on top of Java Swing and AWT, designed
    to make creating simple 2D games easier.
  </p>

  <br />

  <h2>What is SwingSet Engine?</h2>

  <p>
    SwingSet Engine is a Java-based 2D game engine that brings together useful
    UI components and helper methods for game development. Instead of spending
    time setting up and organizing everything yourself, SwingSet provides a
    foundation that helps you focus on what really matters: making games.
  </p>

  <p>
    The engine is particularly useful for developers who are learning Java and
    have recently started exploring the Swing or AWT frameworks. It provides a
    way to move beyond traditional desktop applications and experiment with
    creating interactive 2D games.
  </p>

  <br />

  <h2>What makes it different?</h2>

  <p>
    Unlike many game engines that hide their underlying functionality behind
    complex abstractions, SwingSet Engine keeps things relatively close to the
    original Java frameworks.
  </p>

  <p>
    You still work with Java's own AWT and Swing methods, including the Graphics
    class. The engine simply brings useful functionality together in one place,
    making it quicker to get started without hiding how things work behind the
    scenes.
  </p>

  <br />

  <h2>Key Features</h2>

  <p>
    SwingSet Engine includes several features designed to make simple game
    development more convenient:
  </p>

  <ul>
    <li>
      <strong>Custom Cursor Support:</strong>
      Create and use completely custom cursors in your games.
    </li>

    <li>
      <strong>Custom UI Components:</strong>
      Reimplemented UI elements that share the same graphical context.
    </li>

    <li>
      <strong>Menu Management:</strong>
      A menu management system to help organize your game's menus.
    </li>

    <li>
      <strong>Java Graphics Integration:</strong>
      Continue working with familiar AWT and Swing functionality when building your
      games.
    </li>
  </ul>

  <br />

  <h2>Who is it for?</h2>

  <p>
    SwingSet Engine is a great starting point for Java beginners, students, and
    hobby developers who want to explore the basics of 2D game development.
  </p>

  <p>
    If you already have some experience with Java Swing or AWT, this engine can
    help you take the next step and start experimenting with game mechanics,
    interfaces, and interactive applications.
  </p>
