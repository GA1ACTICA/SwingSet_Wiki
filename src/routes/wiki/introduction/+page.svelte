<h1>Introduction</h1>
<br />

<p>
  Welcome! In this wiki, you will learn how to use SwingSet Engine and explore
  the possibilities it offers for creating your own 2D games using Java Swing
  and AWT.
</p>

<br />

<p>
  Throughout this series, we will go through the fundamentals of the engine,
  explore its different features, and learn how to put them together to create
  something of your own. You will also learn how to build custom UI components
  from scratch or expand upon existing ones to better suit the needs of your
  game. After all, every game has its own style and requirements.
</p>

<br />

<p>
  Of course, no game engine is without its limitations. Since SwingSet Engine is
  built on top of Java's Swing API, there are certain restrictions that you will
  encounter along the way. We will take a closer look at these limitations.
</p>

<br />

<p>
  However, limitations aren't necessarily a bad thing! Swing provides a
  relatively straightforward environment to work in, and some of the more
  advanced features found in larger game engines simply aren't applicable to
  what SwingSet aims to accomplish. This allows us to focus on the fundamentals
  of game development without getting overwhelmed by unnecessary complexity.
</p>

<br />

<p>
  The goal isn't to build the next AAA game. Instead, it's to understand how
  games work, learn how to use the tools available to us, and have fun creating
  something along the way.
</p>

<br />

<p>
  So, whether you're completely new to game development or already have some
  experience with Java, I hope this wiki gives you the knowledge and inspiration
  to start building your own games.
</p>

<br />

<p>But without further ado, let's begin the game-making process!</p>
